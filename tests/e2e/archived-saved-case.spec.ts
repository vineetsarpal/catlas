import { test, expect } from '@playwright/test';
import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import { gunzipSync } from 'node:zlib';
import { openLocations } from '../helpers/exposure-workspace';

test('a complete investigation retains the genuine archived Ridgecrest grid through explicit capture assess and save', async ({ page }, info) => {
  const detailBytes = await fs.readFile('frontend/public/evidence/ridgecrest-detail.geojson');
  const gridBytes = gunzipSync(await fs.readFile('frontend/public/evidence/shaking/ridgecrest-grid.xml.gz'));
  const detail = JSON.parse(detailBytes.toString());
  const event = { id: detail.id, aliases: detail.properties.ids.split(',').filter(Boolean), name: detail.properties.place, magnitude: detail.properties.mag, longitude: detail.geometry.coordinates[0], latitude: detail.geometry.coordinates[1], occurredAt: new Date(detail.properties.time).toISOString(), updatedAt: new Date(detail.properties.updated).toISOString(), significance: 1646 };
  const original = (bytes: Buffer, kind: string) => { const sha256 = createHash('sha256').update(bytes).digest('hex'); return { sha256, bytes: bytes.length, path: `/api/artifacts/${sha256}`, sourceUrl: kind === 'grid' ? 'https://earthquake.usgs.gov/product/shakemap/ci38457511/atlas/1594160054783/download/grid.xml' : 'https://earthquake.usgs.gov/earthquakes/feed/v1.0/detail/ci38457511.geojson', contentType: kind === 'grid' ? 'application/xml' : 'application/geo+json' }; };
  const artifacts = { detail: original(detailBytes, 'detail'), grid: original(gridBytes, 'grid') };
  const requests: { method: string; body: unknown; url: string }[] = [];
  await page.route('**/api/exposure/**', route => {
    const request = route.request(), url = new URL(request.url());
    requests.push({ method: request.method(), body: request.postData() ? request.postDataJSON() : null, url: url.pathname });
    if (url.pathname.endsWith('/catalog')) return route.fulfill({ json: { events: [event], checkedAt: '2026-10-26T20:00:00.000Z', range: { start: '2019-07-01T00:00:00.000Z', end: '2019-07-07T23:59:59.999Z' }, offset: 0, limit: 50, hasMore: false, completeness: 'complete', rejected: 0 } });
    if (url.pathname.endsWith('/captures')) return route.fulfill({ status: 201, json: { schemaVersion: 1, event, product: { id: 'urn:usgs-product:atlas:shakemap:ci38457511:1594160054783', source: 'atlas', code: event.id, updatedAt: '2020-07-07T22:14:14.783Z', retrospective: true }, capturedAt: '2026-10-26T20:00:00.000Z', artifacts } });
    return route.fulfill({ body: url.pathname.endsWith(artifacts.grid.sha256) ? gridBytes : detailBytes });
  });
  await page.goto('/exposure.html');
  await page.getByRole('button', { name: 'Portfolios', exact: true }).click();
  await page.getByRole('button', { name: 'Use demo portfolio', exact: true }).click();
  await page.getByRole('button', { name: 'Exposure', exact: true }).click();
  await page.getByRole('button', { name: /Ridgecrest Earthquake Sequence/ }).click();
  const inspector = page.getByRole('complementary', { name: 'Earthquake evidence inspector' });
  await expect(inspector).toContainText('f4fbcf36e9098963ddc2ea82656974c268b50df5dfdb49b9bf9ffae72ea8e306', { timeout: 30_000 });
  await expect(page.getByTestId('exposure-count')).toHaveText('—');
  await expect(page.getByRole('button', { name: 'Save investigation', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Assess portfolio', exact: true }).click();
  await expect(page.getByTestId('exposure-count')).toHaveText('11');
  await expect(page.getByTestId('exposure-unknown')).toHaveText('2');
  await page.getByRole('button', { name: 'Save investigation', exact: true }).click();
  await openLocations(page);
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download self-contained case', exact: true }).click();
  const download = await pending;
  await fs.mkdir('docs.local/research', { recursive: true });
  const savedPath = `docs.local/research/cat51-ridgecrest-saved-${info.project.name}.json.gz`;
  await download.saveAs(savedPath);
  const envelope = JSON.parse(gunzipSync(await fs.readFile(savedPath)).toString());
  expect(envelope.record.summary).toEqual({ total: 18, meetingThreshold: 11, belowThreshold: 5, unknownIntensity: 2, knownValueByCurrency: { USD: 128000000 }, unknownValueCount: 1 });
  expect(envelope.record.settings).toEqual({ threshold: 4, sampler: 'bilinear-mmi-axes-1' });
  expect(envelope.record.portfolio.asOf).toBe('2019-07-05');
  expect(envelope.record.evidence.rawSha256).toBe('f4fbcf36e9098963ddc2ea82656974c268b50df5dfdb49b9bf9ffae72ea8e306');
  expect(createHash('sha256').update(envelope.rawXml).digest('hex')).toBe(artifacts.grid.sha256);
  expect(envelope.rawEventJson).toBe(detailBytes.toString());
  expect(requests.filter(item => item.method === 'POST')).toEqual([{ method: 'POST', body: { eventId: 'ci38457511' }, url: '/api/exposure/captures' }]);
});
