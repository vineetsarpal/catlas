import { openRecoveryAssessment, openRecoveryHistory, openRecoveryDetails } from '../helpers/recovery-workspace';
import { test, expect, type Page, type Locator } from '@playwright/test';
import fs from 'node:fs/promises';
async function download(page:Page, button:Locator) {
 const pending=page.waitForEvent('download');await button.click();const file=await pending;
 return fs.readFile((await file.path())!,'utf8');
}
test('simulated evidence and imported terms require fresh review and preserve downloaded history',async({page})=>{
 await page.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort());
 await page.goto('/?mode=recovery&recovery=parametric');
 const revisions=page.getByRole('region',{name:'Versioned input revisions'});
 await openRecoveryAssessment(page); await revisions.getByRole('button',{name:/Start simulated M6.9/}).click();
 await expect(page.getByTestId('treaty-total')).toHaveText('$4,000,000');
 await openRecoveryAssessment(page); await expect(revisions).toContainText('not actual USGS bulletin chronology');
 await openRecoveryDetails(page); await page.getByRole('button',{name:'Review evaluation v1',exact:true}).click();
 const firstBytes=await download(page,page.getByRole('button',{name:'Download reviewed JSON',exact:true}));const first=JSON.parse(firstBytes);
 expect(first.evaluation.event.provenance.kind).toBe('simulation');
 expect(first.evaluation.event.provenance.capturedAt).toBeUndefined();
 expect(first.evaluation.event.magnitude).toBe(6.9);
 await openRecoveryAssessment(page); await revisions.getByRole('button',{name:/Apply captured M7.1/}).click();
 await expect(page.getByTestId('treaty-total')).toHaveText('$6,000,000');
 await openRecoveryDetails(page); await expect(page.getByRole('button',{name:'Download reviewed JSON',exact:true})).toBeDisabled();
 await openRecoveryDetails(page); await expect(page.getByRole('button',{name:'Review evaluation v2',exact:true})).toBeEnabled();
 await openRecoveryDetails(page); await page.getByRole('button',{name:'Review evaluation v2',exact:true}).click();
 const secondBytes=await download(page,page.getByRole('button',{name:'Download reviewed JSON',exact:true}));const second=JSON.parse(secondBytes);
 expect(second.evaluation.previousEvaluationId).toBe(first.evaluation.id);
 expect(second.evaluation.event.provenance.kind).toBe('historical');
 expect(second.evaluation.event.magnitude).toBe(7.1);expect(second.packetId).not.toBe(first.packetId);
 for(const key of ['latitude','longitude','occurredAt'])expect(second.evaluation.event[key]).toBe(first.evaluation.event[key]);
 await openRecoveryAssessment(page); await revisions.getByRole('button',{name:/Import fictional RAS terms v3/}).click();
 await expect(page.getByTestId('treaty-total')).toHaveText('$0');
 await openRecoveryDetails(page); await expect(page.getByRole('button',{name:'Download reviewed JSON',exact:true})).toBeDisabled();
 await openRecoveryDetails(page); await page.getByRole('button',{name:'Review evaluation v3',exact:true}).click();
 const zero=JSON.parse(await download(page,page.getByRole('button',{name:'Download reviewed JSON',exact:true})));
 expect(zero.evaluation.contract.id).toBe(first.evaluation.contract.id);
 expect(zero.evaluation.contract.version).toBe(3);expect(zero.evaluation.previousEvaluationId).toBe(second.evaluation.id);
 expect(zero.aggregation.totalRecovery).toBe(0);
 await page.reload();await expect(page.getByTestId('retained-evaluation')).toHaveCount(3);
 await openRecoveryHistory(page); expect(await download(page,page.getByRole('button',{name:`Download archived reviewed packet ${first.packetId.slice(0,8)}`,exact:true}))).toBe(firstBytes);
 await openRecoveryHistory(page); expect(await download(page,page.getByRole('button',{name:`Download archived reviewed packet ${second.packetId.slice(0,8)}`,exact:true}))).toBe(secondBytes);
 await openRecoveryHistory(page); await page.getByTestId('retained-evaluation').filter({hasText:'evaluation v2'}).getByRole('button').click();
 await expect(page.getByTestId('treaty-total')).toHaveText('$6,000,000');
 await openRecoveryDetails(page); expect(await download(page,page.getByRole('button',{name:'Download reviewed JSON',exact:true}))).toBe(secondBytes);
 await openRecoveryAssessment(page); await revisions.getByRole('button',{name:/Import incomplete fictional RAS terms v4/}).click();
 await expect(page.getByTestId('treaty-total')).toHaveText('Indeterminate');
 await openRecoveryDetails(page); await expect(page.getByRole('button',{name:'Prepare exception packet',exact:true})).toBeEnabled();
 await openRecoveryDetails(page); await expect(page.getByRole('button',{name:'Review evaluation v4',exact:true})).toHaveCount(0);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:`/private/tmp/catlas-revisions-${await page.evaluate(()=>innerWidth)}.png`,fullPage:true});
});
